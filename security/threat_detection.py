def simulate_attack(session_id: str, attack_type: str, attacker: str):
    """
    Simulate a cyber attack against a quantum-signed session using Qiskit Aer and PennyLane:
    - Runs Qiskit Aer with simulated eavesdropper measurement for channel attacks
    - Evaluates threat severity using the PennyLane Variational Quantum Classifier
    - Logs security event and returns comprehensive quantum telemetry
    """
    row = one("SELECT * FROM signatures WHERE session_id=?", (session_id,))
    if not row:
        return {"ok": False, "error": "Session not found. Generate a signature first."}

    attack_type = attack_type.lower().strip()
    attack_def = ATTACK_TYPES.get(attack_type)

    if not attack_def:
        valid_types = ", ".join(sorted(ATTACK_TYPES.keys()))
        return {
            "ok": False,
            "error": f"Unknown attack type '{attack_type}'. Valid types: {valid_types}",
        }

    category = attack_def["category"]
    noisy_fidelity = None
    circuit_diagram = None

    # For channel manipulation: execute actual noisy Qiskit Aer circuit with Eve interception
    if attack_type == "channel":
        noisy_res = simulate_teleportation(message=row["message"], signer=row["signer"], eavesdrop=True)
        noisy_fidelity = noisy_res["measurement_match"]
        circuit_diagram = noisy_res["circuit_diagram"]
        # Update session with collapsed fidelity
        execute("UPDATE signatures SET measurement_match=? WHERE session_id=?", (noisy_fidelity, session_id))
        details = (
            f"Quantum channel manipulation simulated on Qiskit Aer. Transit qubit intercepted by Eve; "
            f"teleportation fidelity collapsed to {noisy_fidelity}% (below 80% threshold)."
        )
    elif "detail_fn" in attack_def:
        details = attack_def["detail_fn"](row, attacker)
    else:
        details = attack_def["detail"]

    # Evaluate PennyLane QNN threat score
    current_fid = (noisy_fidelity / 100.0) if noisy_fidelity is not None else (row["measurement_match"] / 100.0)
    qnn_res = evaluate_quantum_threat(
        message=row["message"],
        signer=attacker if attack_type == "impersonation" else row["signer"],
        fidelity=current_fid,
        is_consumed=True if attack_type == "replay" else bool(row["consumed"]),
        is_authorized=False if attack_type in ("unauthorized", "impersonation") else True,
    )
    score = qnn_res["threat_score"]

    log_event(session_id, category, attacker, score, details)

    knowledge = ATTACK_KNOWLEDGE_BASE.get(attack_type, {})

    return {
        "ok": True,
        "session_id": session_id,
        "attacker": attacker,
        "category": category,
        "decision": "REJECT",
        "threat_score": score,
        "reason": details,
        "quantum_engine": {
            "simulator": "Qiskit Aer (AerSimulator)",
            "qnn_framework": "PennyLane 0.45",
            "fidelity": noisy_fidelity if noisy_fidelity is not None else row["measurement_match"],
            "circuit_diagram": circuit_diagram or row.get("circuit_diagram"),
        },
        "attack_info": {
            "name": knowledge.get("name", category),
            "icon": knowledge.get("icon", "⚠️"),
            "severity": knowledge.get("severity", "UNKNOWN"),
            "description": knowledge.get("description", ""),
            "how_it_works": knowledge.get("how_it_works", []),
            "real_world_example": knowledge.get("real_world_example", ""),
            "countermeasures": knowledge.get("countermeasures", []),
            "quantum_defense": knowledge.get("quantum_defense", ""),
        },
    }
